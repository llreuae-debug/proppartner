// Helper to format currency
export function formatCurrency(amount, currency = 'PKR') {
  if (currency === 'USD') {
    const usdAmount = Math.round(amount / 280);
    return `$${usdAmount.toLocaleString('en-US')}`;
  } else if (currency === 'AED') {
    const aedAmount = Math.round(amount / 76);
    return `AED ${aedAmount.toLocaleString('en-US')}`;
  } else {
    // PKR format with Million / Lacs or formatted number
    if (amount >= 10000000) {
      const crore = (amount / 10000000).toFixed(2);
      return `PKR ${amount.toLocaleString('en-US')} (${crore} Cr)`;
    }
    return `PKR ${amount.toLocaleString('en-US')}`;
  }
}

export function formatCompactCurrency(amount, currency = 'PKR') {
  if (currency === 'USD') {
    const usd = amount / 280;
    if (usd >= 1000000) return `$${(usd / 1000000).toFixed(1)}M`;
    if (usd >= 1000) return `$${(usd / 1000).toFixed(0)}K`;
    return `$${Math.round(usd)}`;
  }
  if (currency === 'AED') {
    const aed = amount / 76;
    if (aed >= 1000000) return `AED ${(aed / 1000000).toFixed(1)}M`;
    if (aed >= 1000) return `AED ${(aed / 1000).toFixed(0)}K`;
    return `AED ${Math.round(aed)}`;
  }
  if (amount >= 10000000) {
    return `PKR ${(amount / 10000000).toFixed(2)} Cr`;
  }
  if (amount >= 100000) {
    return `PKR ${(amount / 100000).toFixed(1)} Lac`;
  }
  return `PKR ${amount.toLocaleString('en-US')}`;
}
